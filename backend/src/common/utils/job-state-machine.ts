// Job state machine — PRD p.8. Strict: only listed transitions are legal.
// Illegal transitions are rejected with 409 AND still written to job_events
// (the service layer records the rejected attempt before throwing).
export type JobState =
  | 'DRAFT' | 'BROADCASTING' | 'OFFERS_RECEIVED' | 'ACCEPTED'
  | 'PROVIDER_EN_ROUTE' | 'CUSTOMER_EN_ROUTE' | 'ITEM_PICKED_UP'
  | 'ARRIVED' | 'IN_PROGRESS' | 'PRICE_ADJUSTMENT_PENDING'
  | 'COMPLETED' | 'PAYMENT_SETTLED' | 'RATED'
  | 'CANCELLED_BY_CUSTOMER' | 'CANCELLED_BY_PROVIDER' | 'EXPIRED' | 'DISPUTED' | 'REFUNDED';
export const TERMINAL_STATES: JobState[] = ['RATED', 'CANCELLED_BY_CUSTOMER', 'CANCELLED_BY_PROVIDER', 'EXPIRED', 'REFUNDED'];
const TRANSITIONS: Record<JobState, JobState[]> = {
  DRAFT: ['BROADCASTING', 'CANCELLED_BY_CUSTOMER', 'EXPIRED'],
  BROADCASTING: ['OFFERS_RECEIVED', 'ACCEPTED', 'CANCELLED_BY_CUSTOMER', 'EXPIRED'],
  OFFERS_RECEIVED: ['ACCEPTED', 'BROADCASTING', 'CANCELLED_BY_CUSTOMER', 'EXPIRED'],
  ACCEPTED: ['PROVIDER_EN_ROUTE', 'CUSTOMER_EN_ROUTE', 'ITEM_PICKED_UP', 'CANCELLED_BY_CUSTOMER', 'CANCELLED_BY_PROVIDER', 'DISPUTED'],
  PROVIDER_EN_ROUTE: ['ARRIVED', 'CANCELLED_BY_CUSTOMER', 'CANCELLED_BY_PROVIDER', 'DISPUTED'],
  CUSTOMER_EN_ROUTE: ['ARRIVED', 'CANCELLED_BY_CUSTOMER', 'CANCELLED_BY_PROVIDER', 'DISPUTED'],
  ITEM_PICKED_UP: ['ARRIVED', 'IN_PROGRESS', 'CANCELLED_BY_CUSTOMER', 'CANCELLED_BY_PROVIDER', 'DISPUTED'],
  ARRIVED: ['IN_PROGRESS', 'CANCELLED_BY_CUSTOMER', 'CANCELLED_BY_PROVIDER', 'DISPUTED'],
  IN_PROGRESS: ['PRICE_ADJUSTMENT_PENDING', 'COMPLETED', 'CANCELLED_BY_CUSTOMER', 'CANCELLED_BY_PROVIDER', 'DISPUTED'],
  PRICE_ADJUSTMENT_PENDING: ['IN_PROGRESS', 'CANCELLED_BY_CUSTOMER', 'CANCELLED_BY_PROVIDER', 'DISPUTED'],
  COMPLETED: ['PAYMENT_SETTLED', 'DISPUTED'],
  PAYMENT_SETTLED: ['RATED', 'DISPUTED', 'REFUNDED'],
  RATED: [],
  CANCELLED_BY_CUSTOMER: [], CANCELLED_BY_PROVIDER: [], EXPIRED: [], DISPUTED: ['REFUNDED', 'PAYMENT_SETTLED', 'IN_PROGRESS'], REFUNDED: [],
};
export function isLegalTransition(from: JobState, to: JobState): boolean {
  return (TRANSITIONS[from] ?? []).includes(to);
}
export function legalNextStates(from: JobState): JobState[] {
  return [...(TRANSITIONS[from] ?? [])];
}
